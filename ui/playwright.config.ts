import { defineConfig, devices } from '@playwright/test'

/**
 * Browser smoke test of the demo flow. Every /api route is mocked in the
 * test with `page.route`, so no Python backend, model or data is needed:
 * only the Vite dev server, which Playwright starts on a spare port.
 */
const PORT = Number(process.env.DFSI_E2E_PORT ?? 5199)

export default defineConfig({
  testDir: './e2e',
  timeout: 30_000,
  fullyParallel: true,
  forbidOnly: Boolean(process.env.CI),
  retries: process.env.CI ? 1 : 0,
  reporter: process.env.CI ? [['list'], ['html', { open: 'never' }]] : 'list',
  use: {
    baseURL: `http://127.0.0.1:${PORT}`,
    trace: 'retain-on-failure',
  },
  projects: [{ name: 'chromium', use: { ...devices['Desktop Chrome'] } }],
  webServer: {
    command: `npx vite --port ${PORT} --strictPort --host 127.0.0.1`,
    url: `http://127.0.0.1:${PORT}`,
    reuseExistingServer: !process.env.CI,
    timeout: 60_000,
  },
})
